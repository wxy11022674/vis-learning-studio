  assert.equal(await page.locator('[data-hero-mode="line"]').getAttribute('aria-pressed'),'true');
  assert.equal(await page.locator('#hero-stage circle').count(),12);
  await page.locator('[data-hero-mode="dot"]').click();
  assert.equal(await page.locator('#hero-stage circle').count(),12);
