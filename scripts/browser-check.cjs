  await mobile.getByRole('button',{name:'打开导航'}).click();
  assert.ok((await mobile.locator('#sidebar').getAttribute('class')).includes('open'));
  await mobile.locator('#sidebar').getByRole('link',{name:'课程章节'}).click();
  assert.ok(!(await mobile.locator('#sidebar').getAttribute('class')).includes('open'));
  await mobile.goto(base+'/#notebook');
  await mobile.locator('#backup-file').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
