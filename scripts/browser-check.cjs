  await page.locator('.search-result').first().click();
  await page.waitForURL('**/#lesson/1/4');
  await page.getByRole('button',{name:'收藏本节'}).click();
  await page.getByRole('button',{name:'标记学会',exact:true}).click();
  await page.getByRole('tab',{name:'我的笔记'}).click();
  await page.locator('#lesson-note').fill('测试笔记：key 保持身份；<script>不可执行</script>');
  await page.waitForTimeout(650);
  await page.reload();
  await page.getByRole('tab',{name:'我的笔记'}).click();
  assert.equal(await page.locator('#lesson-note').inputValue(),'测试笔记：key 保持身份；<script>不可执行</script>');
  await goto('#notebook');
  assert.equal(await page.locator('.note-card').count(),1);
  assert.ok((await page.locator('.note-card').textContent()).includes('<script>不可执行</script>'));
  await page.getByRole('link',{name:'编辑笔记'}).click();
  assert.equal(await page.locator('#lesson-note').count(),1);
  await goto('#lesson/3/1');
  await page.getByRole('button',{name:'增大正文字号'}).click();
  assert.equal(await page.locator('#reading-size').textContent(),'17px');
