  await page.keyboard.press('Escape');
  assert.equal(await page.locator('body').evaluate(b=>b.classList.contains('reading-focus')),false);
  await page.getByRole('button',{name:'减小正文字号'}).click();
  await page.screenshot({path:'artifacts/desktop-lesson.png',fullPage:true,animations:'disabled'});
  // Every local lesson route must show the correct title and substantive content.
  const structure=await page.evaluate(()=>window.VIS_COURSE.map(c=>({id:c.id,n:c.sections.length})));
  for(const c of structure)for(let i=0;i<c.n;i++){
    await goto(`#lesson/${c.id}/${i}`);
    assert.ok(await page.locator('.lesson-body>p').count()>=2);
    assert.ok((await page.locator('.lesson-title h1').textContent()).startsWith(`${c.id}.${i+1}`));
  }
  await goto('#lab/encoding');
  assert.equal(await page.locator('#chart-stage svg').count(),1);
  await page.locator('#control-sort').selectOption('desc');
  const before=await page.locator('#chart-stage svg').innerHTML();
  await page.locator('[data-lab-setting="baseline"]').uncheck();
  assert.notEqual(await page.locator('#chart-stage svg').innerHTML(),before);
  await page.locator('#control-type').selectOption('dot');
  assert.equal(await page.locator('#chart-stage circle').count(),6);
  await page.locator('#control-dataset').selectOption('books');
  assert.equal(await page.locator('#chart-stage circle').count(),7);
