  await page.evaluate(()=>document.querySelector('#toast').classList.remove('visible'));
  await page.screenshot({path:'artifacts/desktop-lab.png',fullPage:true});
  await goto('#lab/calendar');
  assert.equal(await page.locator('#chart-stage [data-tip]').count(),365);
  const calendarBefore=await page.locator('.calendar-hint').textContent();
  await page.locator('#control-threshold').fill('60');
  await page.locator('#control-threshold').dispatchEvent('input');
  assert.notEqual(await page.locator('.calendar-hint').textContent(),calendarBefore);
  await goto('#charts');assert.equal(await page.locator('.guide-card').count(),6);
  await page.getByRole('button',{name:'发现周期',exact:true}).click();
  assert.equal(await page.locator('.guide-card').count(),1);
